    /**
     * Trazado del circuito ya calibrado —meta en la fracción 0 y puntos en el
     * sentido de la marcha—, o {@code null} si no hay calco para ese nombre.
     * Quien lo pinte debe tolerar el nulo: un circuito dado de alta desde el CRUD
     * no tiene trazado.
     */
    public static TrackLayout de(String circuito) {
        Trazado trazado = circuito == null ? null : TRAZADOS.get(circuito);
        return trazado == null ? null : TrackLayout.desdePuntosDeControl(
                calibrar(trazado.puntos(), trazado.meta(), trazado.invertido()));
    }

    /**
     * Gira el lazo para que la meta quede en el índice 0 y, si hace falta, lo
     * invierte. Los puntos vienen equiespaciados por longitud de arco, así que
     * girar {@code meta · n} posiciones equivale a girar esa fracción de vuelta.
     */
    private static double[][] calibrar(double[][] puntos, double meta, boolean invertido) {
        int n = puntos.length;
        double[][] ordenados = new double[n][];
        for (int i = 0; i < n; i++) {
            ordenados[i] = invertido ? puntos[n - 1 - i] : puntos[i];
        }
        int desfase = Math.floorMod((int) Math.round(meta * n), n);
        double[][] salida = new double[n][];
        for (int i = 0; i < n; i++) {
            salida[i] = ordenados[(i + desfase) % n];
        }
        return salida;
    }

    /** Nombres con trazado disponible. Lo usan las pruebas. */
    public static Set<String> conTrazado() {
        return TRAZADOS.keySet();
    }
