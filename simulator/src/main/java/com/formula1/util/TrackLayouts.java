/**
 * Trazados de los siete circuitos del catálogo.
 *
 * <p>Los puntos no están puestos a mano: los genera {@code tools/TrazarCircuitos.java}
 * calcando los mapas oficiales que ya viven en {@code /images/circuits/}. Si se
 * cambia el mapa de un circuito, se vuelve a correr esa herramienta y se pega su
 * salida aquí. Existe por lo mismo que {@code gen_seed.py}: que los números sean
 * auditables y reproducibles en vez de constantes llovidas del cielo.
 *
 * <p>Coordenadas normalizadas con la Y hacia abajo, como en pantalla, y escaladas
 * por el lado mayor de la caja envolvente: el eje largo ocupa [0,1] y el corto lo
 * que le corresponda, <b>conservando la proporción real del circuito</b>.
 *
 * <p>El trazador entrega el lazo empezando por donde arrancó el contorno y en el
 * sentido en que lo recorrió, que no tienen por qué ser la línea de meta ni el
 * sentido de la marcha. Por eso cada circuito lleva además su {@link Trazado#meta}
 * y su {@link Trazado#invertido}, calibrados contra la bandera a cuadros y las
 * flechas de su mapa oficial. Importa: con el sentido invertido los coches
 * correrían hacia atrás, y con la meta mal puesta los colores de sector no caerían
 * donde el motor los sitúa.
 *
 * <p>Se mantienen en Java y no en {@code seed.json} a propósito: son datos de
 * presentación, no de dominio. En el seed obligarían a versionarlos en MongoDB
 * —que además se carga <em>antes</em> que el seed, así que una base ya existente se
 * quedaría sin trazado—, a mantenerlos también en {@code gen_seed.py}, y no
 * resolverían el circuito que un usuario dé de alta desde el CRUD, que nunca tendrá
 * calco.
 */
